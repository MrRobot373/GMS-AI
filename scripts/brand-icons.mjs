#!/usr/bin/env node
/**
 * Writes apps/web/src/lib/brand-icons.ts: the logo of each app in the connector catalog, from
 * Simple Icons (https://simpleicons.org, CC0-1.0). Only the SVG path data and brand colour are
 * copied; nothing is added to the app's dependencies.
 *
 *   npm pack simple-icons && tar -xzf simple-icons-*.tgz   # → ./package
 *   node scripts/brand-icons.mjs ./package
 *
 * Brands Simple Icons doesn't carry (some asked to be removed: Slack, Canva, Microsoft, AWS…) are
 * left out, and the app shows their initial instead. Logos are trademarks of their owners and are
 * shown only to name the app a connector talks to.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const dir = process.argv[2];
if (!dir) {
  console.error("usage: node scripts/brand-icons.mjs <unpacked simple-icons package>");
  process.exit(1);
}

/** Catalog id (packages/shared/src/connectors.ts) → Simple Icons slug. */
const SLUGS = {
  gmail: "gmail",
  "google-calendar": "googlecalendar",
  calendly: "calendly",
  "google-drive": "googledrive",
  "google-docs": "googledocs",
  "google-sheets": "googlesheets",
  "google-slides": "googleslides",
  notion: "notion",
  dropbox: "dropbox",
  box: "box",
  figma: "figma",
  miro: "miro",
  zoom: "zoom",
  linear: "linear",
  atlassian: "atlassian",
  asana: "asana",
  clickup: "clickup",
  todoist: "todoist",
  hubspot: "hubspot",
  intercom: "intercom",
  stripe: "stripe",
  paypal: "paypal",
  square: "square",
  github: "github",
  "github-token": "github",
  gitlab: "gitlab",
  sentry: "sentry",
  vercel: "vercel",
  netlify: "netlify",
  cloudflare: "cloudflareworkers",
  supabase: "supabase",
  neon: "neon",
  airtable: "airtable",
  huggingface: "huggingface",
  zapier: "zapier",
};

const pkg = JSON.parse(readFileSync(join(dir, "package.json"), "utf8"));
const data = JSON.parse(readFileSync(join(dir, "data/simple-icons.json"), "utf8"));

// The tile behind a logo (theme.css --bg): a brand colour too close to it shows in the text colour instead.
const PAGE = { light: "#fbfbfb", dark: "#0f0f0f" };
const lum = (hex) => {
  const [r, g, b] = [0, 2, 4].map((i) => parseInt(hex.replace("#", "").slice(i, i + 2), 16) / 255).map((c) => (c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4));
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
};
const contrast = (a, b) => {
  const [x, y] = [lum(a), lum(b)].sort((p, q) => q - p);
  return (x + 0.05) / (y + 0.05);
};

const out = {};
for (const [id, slug] of Object.entries(SLUGS)) {
  const icon = data.find((i) => i.slug === slug);
  if (!icon) throw new Error(`Simple Icons ${pkg.version} has no "${slug}" (for ${id})`);
  const svg = readFileSync(join(dir, "icons", `${slug}.svg`), "utf8");
  const path = /<path d="([^"]+)"/.exec(svg)?.[1];
  if (!path) throw new Error(`no path in ${slug}.svg`);
  const hex = `#${icon.hex}`;
  out[id] = {
    title: icon.title,
    path,
    light: contrast(hex, PAGE.light) >= 2 ? hex : null,
    dark: contrast(hex, PAGE.dark) >= 2 ? hex : null,
  };
}

const body = `// Generated by scripts/brand-icons.mjs from Simple Icons ${pkg.version} (CC0-1.0). Don't edit by hand.
// Logos are trademarks of their owners, shown only to name the app a connector talks to.

export interface BrandIcon {
  title: string;
  /** SVG path data on a 24×24 grid. */
  path: string;
  /** Brand colour on each theme; null where it would be too faint (then the text colour). */
  light: string | null;
  dark: string | null;
}

/** By connector catalog id. */
export const BRAND_ICONS: Record<string, BrandIcon> = ${JSON.stringify(out, null, 2)};
`;
writeFileSync(new URL("../apps/web/src/lib/brand-icons.ts", import.meta.url), body);
console.log(`${Object.keys(out).length} logos from Simple Icons ${pkg.version}`);
